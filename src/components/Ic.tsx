const warned = new Set<string>();

export function Ic({
    name,
    className = "h-[24px] w-[24px]",
}: {
    name: string;
    className?: string;
}) {
    const cls = `block flex-none ${className}`;

    const f = FILLED[name];
    if (f) {
        const { d, vb } = typeof f === "string" ? { d: f, vb: "0 0 24 24" } : f;
        return (
            <svg viewBox={vb} fill="currentColor" aria-hidden className={cls}>
                <path d={d} />
            </svg>
        );
    }

    const file = FILES[ALIAS[name] ?? name];
    if (file) {
        return (
            <svg
                viewBox={file.vb}
                fill={file.fill ?? "currentColor"}
                stroke={file.stroke}
                strokeWidth={file.sw}
                strokeLinecap="round"
                strokeLinejoin="round"
                aria-hidden
                className={cls}
                dangerouslySetInnerHTML={{ __html: file.inner }}
            />
        );
    }

    if (import.meta.env.DEV && !warned.has(name)) {
        warned.add(name);
        console.warn(
            `[Ic] no icon file for "${name}". Files in src/icons: ${Object.keys(FILES).join(", ") || "(none found)"}`,
        );
    }
    return (
        <svg
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            strokeWidth={2}
            strokeLinecap="round"
            strokeLinejoin="round"
            aria-hidden
            className={cls}
        >
            {STROKE[name] ?? (
                <rect
                    x="4"
                    y="4"
                    width="16"
                    height="16"
                    strokeDasharray="3 3"
                />
            )}
        </svg>
    );
}
