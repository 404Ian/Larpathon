// ---- 2. every svg in src/icons, read as raw text at build time -------------
// (Vite 5+. On Vite 3/4 replace  { query: "?raw", import: "default", eager: true }  with  { as: "raw", eager: true })
const RAW = import.meta.glob("../icons/*.svg", {
    query: "?raw",
    import: "default",
    eager: true,
}) as Record<string, string>;

type Parsed = {
    vb: string;
    inner: string;
    fill?: string;
    stroke?: string;
    sw?: string;
};
const themed = (v?: string) =>
    !v || v === "none" || v.toLowerCase().startsWith("current")
        ? v
        : "currentColor";

const FILES: Record<string, Parsed> = {};
for (const [path, text] of Object.entries(RAW)) {
    const name = (path.split("/").pop() ?? "").replace(/\.svg$/i, "");
    const root = /<svg([^>]*)>/i.exec(text)?.[1] ?? "";
    const attr = (n: string) =>
        new RegExp(`\\s${n}="([^"]*)"`, "i").exec(root)?.[1];
    FILES[name] = {
        vb: attr("viewBox") ?? "0 0 24 24",
        inner: text
            .replace(/^[\s\S]*?<svg[^>]*>/i, "")
            .replace(/<\/svg>\s*$/i, "")
            .replace(
                /\s(fill|stroke)="(#000(?:000)?|black)"/gi,
                ' $1="currentColor"',
            ),
        fill: themed(attr("fill")),
        stroke: themed(attr("stroke")),
        sw: attr("stroke-width"),
    };
}

